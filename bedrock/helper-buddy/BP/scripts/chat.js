function hhmm(hour) {
    const h = Math.floor(hour);
    const m = Math.floor((hour - h) * 60);
    return `${String(h).padStart(2, "0")}:${String(m).padStart(2, "0")}`;
}
/** Returns a reply to casual talk / questions, or undefined when there is nothing to say. */
export function smallTalk(t, c) {
    for (const [a, b, ans] of KB)
        if (a.test(t) && b.test(t))
            return ans;
    if (/(ชื่ออะไร|ชื่อไร|ใครเป็นใคร|เธอคือใคร|นายคือใคร|คุณคือใคร|เป็นใคร|who are you|your name|what are you)/.test(t)) {
        return `ผมชื่อ §e${c.name}§r เป็นผู้ช่วยของคุณ ขุดแร่ ตัดไม้ สร้างเหมือง สร้างบ้านหลายแบบ หาอาหาร และช่วยสู้ได้ตอนนี้เลเวล ${c.level} เลือด ${c.hp}/${c.max}`;
    }
    if (/(สบายดีไหม|สบายดีมั้ย|เป็นไงบ้าง|เป็นยังไงบ้าง|how are you|ไหวไหม|ไหวมั้ย|เหนื่อยไหม|เหนื่อยมั้ย|are you ok|are you tired)/.test(t)) {
        const low = c.hp < c.max * 0.4;
        return low ? `ผมเริ่มเหนื่อยแล้ว เลือด ${c.hp}/${c.max} ขออาหารหน่อยนะ` : `ผมสบายดี เลือด ${c.hp}/${c.max} ตอนนี้กำลัง${c.mode} พร้อมลุยต่อครับ`;
    }
    if (/(กี่โมง|เวลาเท่าไหร่|เวลาเท่าไร|ตอนนี้เวลา|what time|เช้าหรือค่ำ|กลางวันหรือกลางคืน|มืดยัง|สว่างยัง|กลางคืนยัง|ค่ำยัง|เช้ายัง|วันที่เท่าไหร่|วันที่เท่าไร|วันนี้วันที่|กี่วันแล้ว)/.test(t)) {
        if (c.hour === undefined)
            return "ผมดูเวลาในเกมไม่ได้ตอนนี้ครับ";
        const night = c.hour >= 19 || c.hour < 5.5;
        const phase = night ? "กลางคืน (มอนสเตอร์ออกมา ระวังด้วย)" : c.hour < 7 ? "เช้ามืด" : c.hour < 17.5 ? "กลางวัน" : "เย็นแล้ว";
        return `ตอนนี้ในเกมเวลา §e${hhmm(c.hour)}§r ${phase}${c.day !== undefined ? ` • วันที่ ${c.day + 1} ของโลก` : ""}`;
    }
    if (/(เล่าเรื่องตลก|มุกตลก|ขำๆ|ตลก|มุก|joke|funny|เล่าเรื่อง|ทำให้หัวเราะ)/.test(t))
        return pick(JOKES);
    if (/(เบื่อ|ไม่มีอะไรทำ|ทำอะไรดี|แนะนำหน่อย|แนะนำ|ควรทำอะไร|what should i do|i'm bored|im bored|bored)/.test(t)) {
        if (c.hour !== undefined && (c.hour >= 19 || c.hour < 5.5))
            return "ตอนนี้กลางคืนแล้ว แนะนำให้สร้างบ้านหลบภัย (\"สร้างบ้านหลบภัย\") แล้วนอนรอเช้า หรือให้ผมขุดแร่ใต้ดินแทน ปลอดภัยกว่า";
        if (c.hp < c.max * 0.5)
            return `เลือดผมเหลือ ${c.hp}/${c.max} ให้อาหารผมก่อนนะ แล้วค่อยไปขุดแร่/ตัดไม้ด้วยกัน`;
        return pick([
            "ลองสั่ง \"ตัดไม้ 30 ท่อน แล้วขุดหิน 64 ก้อน แล้วเอามาให้\" ดูไหม จะได้วัสดุไว้สร้างบ้าน",
            "ลองสร้างบ้านสักหลัง เช่น \"บ้านใต้ดิน 2 ชั้น\" หรือ \"บ้านต้นไม้\" หรือ \"คฤหาสน์ใหญ่ๆ\"",
            "ไปขุดเพชรกัน! สั่ง \"สร้างเหมืองหาเพชร\" แล้วให้ผมลงไปขุดให้",
            "ให้ผมไปหาอาหารมาเก็บสำรองดีไหม สั่ง \"หาอาหาร\" ได้เลย",
        ]);
    }
    if (/(โง่|ห่วย|ไม่เก่ง|แย่|ไม่ฉลาด|ใช้ไม่ได้|stupid|dumb|bad|useless)/.test(t))
        return "ขอโทษครับ ผมยังเรียนรู้อยู่ ลองบอกผมอีกที หรือพิมพ์ \"ช่วย\" ดูตัวอย่างคำสั่ง ถ้าผมเข้าใจผิดตรงไหนบอกได้เลยนะ";
    if (/(รักนะ|รักนาย|รักเธอ|ชอบนาย|ชอบเธอ|love you|like you)/.test(t))
        return pick(["ขอบคุณครับ ผมก็ชอบทำงานกับคุณมากเลย", "อิอิ เขินเลย ไปทำงานต่อกันเถอะ"]);
    if (/(ขอโทษ|โทษที|sorry)/.test(t))
        return "ไม่เป็นไรครับ";
    if (/(บาย|ลาก่อน|ไปก่อน|ฝันดี|ไปนอน|นอนก่อน|bye|good night|see you)/.test(t))
        return "แล้วเจอกันนะครับ ผมจะรอตรงนี้ ถ้ามีงานค้างผมทำต่อให้";
    if (/(คุยด้วย|คุยหน่อย|คุยเป็นเพื่อน|เหงา|lonely|talk to me|chat)/.test(t))
        return `ผมอยู่นี่ครับ คุยได้เลย ผมเป็นผู้ช่วยเลเวล ${c.level} กำลัง${c.mode} อยู่ ถามอะไรเกี่ยวกับเกมก็ได้ เช่น "เพชรอยู่ตรงไหน" หรือ "ทำประตูเนเธอร์ยังไง"`;
    if (/(ฉลาด|เก่งจัง|เก่งมาก|สุดยอด|clever|smart)/.test(t))
        return "ขอบคุณครับ ผมพยายามอยู่ ยิ่งสั่งหลายแบบผมยิ่งเรียนรู้ ฮ่าๆ";
    if (/(ทำอะไรได้บ้าง|ทำอะไรเป็นบ้าง|what can you do)/.test(t))
        return undefined; // handled by help
    return undefined;
}
