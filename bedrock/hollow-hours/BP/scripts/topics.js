// เวลาในเกม (0 = 6 โมงเช้า) เป็นภาษาพูด
export function timeText(tod) {
  const h = Math.floor(((tod / 1000) + 6) % 24);
  if (isEn()) {
    if (h === 0) return "midnight";
    if (h === 12) return "noon";
    return `${h > 12 ? h - 12 : h} ${h < 12 ? "AM" : "PM"}`;
  }
  if (h === 0) return "เที่ยงคืน";
  if (h <= 5) return `ตี${NUM[h]}`;
  if (h <= 11) return `${NUM[h]}โมงเช้า`;
  if (h === 12) return "เที่ยงวัน";
  if (h <= 15) return `บ่าย${h === 13 ? "" : NUM[h - 12]}โมง`;
  if (h <= 18) return `${NUM[h - 12]}โมงเย็น`;
  return `${NUM[h - 18]}ทุ่ม`;
}
// ทิศที่ผีอยู่ เทียบกับทางที่ผู้เล่นหัน
export function dirText(p, g) {
  try {
    const dx = g.location.x - p.location.x, dz = g.location.z - p.location.z, dy = g.location.y - p.location.y;
    if (Math.hypot(dx, dz) < 3 && Math.abs(dy) > 3) return isEn() ? (dy > 0 ? "above" : "below") : (dy > 0 ? "ข้างบน" : "ข้างล่าง");
    const yaw = (p.getRotation().y * Math.PI) / 180;
    const fx = -Math.sin(yaw), fz = Math.cos(yaw);
    const fwd = (dx * fx + dz * fz), right = (dx * -fz + dz * fx);
    if (Math.abs(fwd) >= Math.abs(right)) return isEn() ? (fwd >= 0 ? "in front of" : "behind") : (fwd >= 0 ? "ข้างหน้า" : "ข้างหลัง");
    return isEn() ? (right >= 0 ? "to the right of" : "to the left of") : (right >= 0 ? "ทางขวา" : "ทางซ้าย");
  } catch (_) { return isEn() ? "near" : "ใกล้ ๆ"; }
}
